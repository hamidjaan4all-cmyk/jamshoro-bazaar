def tr(key, lang="en"):
    """Return the (en, ur) tuple's value for lang ('en' or 'ur')."""
    pair = STRINGS.get(key, (key, key))
    return pair[1] if lang == "ur" else pair[0]


def lang_from_request(args, cookies):
    lang = args.get("lang")
    if lang in ("en", "ur"):
        return lang
    return cookies.get("jb_lang", "en")
